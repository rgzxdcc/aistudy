# -*- coding: utf-8 -*-
"""
模块3 · 第1课：Series 与 DataFrame
==================================
Pandas 是 Python 数据分析的"Excel"。两大核心对象：
- Series   一维带标签数组（相当于"一列"）
- DataFrame 二维表格（相当于"一张表"），由多个 Series 组成

约定俗成：import pandas as pd   ← 全世界都这么写。
"""
import numpy as np
import pandas as pd


# ============================================================
# 一、Series —— 带索引的一维数组
# ============================================================
# Series = NumPy 数组 + 自定义索引（标签）

# 1.1 从列表创建（默认索引 0,1,2,...）
s = pd.Series([85, 92, 78, 90])
print("默认索引:\n", s)
print("类型:", type(s))

# 1.2 指定索引（这是 Series 的精髓：用"标签"而非"位置"访问）
scores = pd.Series([85, 92, 78, 90],
                   index=["小明", "小红", "小刚", "小华"])
print("\n带标签索引:\n", scores)

# 用标签访问（像字典）
print("\n小红的分数:", scores["小红"])
print("多取几个:\n", scores[["小明", "小华"]])

# 1.3 从字典创建（最自然，键变索引）
data = {"语文": 88, "数学": 95, "英语": 82}
s2 = pd.Series(data)
print("\n从字典创建:\n", s2)

# Series 保留 NumPy 的向量化运算
print("\n分数加 5 分:\n", scores + 5)
print("平均分:", scores.mean())


# ============================================================
# 二、DataFrame —— 二维表格（ML 最常用的数据结构）
# ============================================================
# DataFrame 像数据库表/Excel 表：有行索引、有列名。

# 2.1 从字典创建（最常用）
df = pd.DataFrame({
    "姓名":   ["小明", "小红", "小刚", "小华"],
    "年龄":   [20, 21, 19, 22],
    "分数":   [85, 92, 78, 90],
    "是否及格": [True, True, False, True],
})
print("\n=== DataFrame ===")
print(df)
print("类型:", type(df))

# 2.2 关键属性（必须熟记！）
print("\nshape 形状:", df.shape)        # (4, 4) = 4行×4列
print("columns 列名:", list(df.columns))
print("index 行索引:", list(df.index))
print("dtypes 各列类型:\n", df.dtypes)

# 2.3 从 NumPy 数组创建（ML 中很常见：X 矩阵转成 DataFrame）
arr = np.random.randint(0, 100, (5, 3))
df_from_arr = pd.DataFrame(arr, columns=["特征A", "特征B", "特征C"])
print("\n从数组创建:\n", df_from_arr.head(3))   # head 默认看前 5 行，这里看 3 行


# ============================================================
# 三、DataFrame 的快速查看（拿到新数据第一步）
# ============================================================
# 真实数据动辄几万行，必须用工具快速"摸底"

# head(n) / tail(n)：看前/后 n 行（默认 5）
print("\n前 2 行:\n", df.head(2))
print("后 2 行:\n", df.tail(2))

# info()：看列名、类型、非空数量、内存占用（找缺失值第一步）
print("\n--- info() ---")
df.info()

# describe()：数值列的统计摘要（均值/标准差/最值/分位数）
print("\n--- describe() ---")
print(df.describe())


# ============================================================
# 四、列的增删改（数据预处理高频操作）
# ============================================================
# 【重要】DataFrame 的多数操作返回新对象（不原地修改），用 inplace=True 才改原表

# 4.1 选列（返回 Series）
ages = df["年龄"]
print("\n选'年龄'列:\n", ages)

# 4.2 新增列（向量式赋值，不用循环）
df["分数加成"] = df["分数"] * 1.1          # 每行都乘 1.1（广播）
print("\n新增列后:\n", df)

# 用 np.where 做条件新增列（数据清洗常用）
df["等级"] = np.where(df["分数"] >= 90, "优秀",
                np.where(df["分数"] >= 60, "及格", "不及格"))
print("\n条件新增'等级':\n", df[["姓名", "分数", "等级"]])

# 4.3 删除列：drop(axis=1) 或 drop(columns=...)
df2 = df.drop(columns=["分数加成"])         # 默认返回新表，不改原表
print("\n删除'分数加成'列后:\n", df2)

# 4.4 修改值
df.loc[0, "分数"] = 95                      # 第0行的分数改成95
print("\n修改第0行分数:\n", df.loc[0])


# ============================================================
# 五、索引对象 Index（行标签）
# ============================================================
# 索引可以自定义，比如用学号当行索引

df_idx = df.set_index("姓名")               # 把'姓名'列设为行索引
print("\n设姓名为索引后:\n", df_idx)
print("按索引取行 df_idx.loc['小红']:\n", df_idx.loc["小红"])

# 重置索引
df_reset = df_idx.reset_index()
print("\n重置索引:\n", df_reset[["姓名", "年龄"]].head(2))


# ============================================================
# 小结：本课你应掌握的"ML 高频"操作
# ============================================================
# 1. pd.Series([...], index=[...]) 创建带标签的一维数据
# 2. pd.DataFrame({...}) 从字典创建表格（最常用）
# 3. df.shape / columns / dtypes / head / info / describe 摸底数据
# 4. df["列名"] 选列；df["新列"] = ... 新增列（向量化）
# 5. drop(columns=...) 删列；set_index 设索引；loc 按标签取行
