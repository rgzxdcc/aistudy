import numpy as np
from sklearn.datasets import load_iris      # 经典鸢尾花数据集
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score


# ============================================================
# 一、机器学习在做什么？
# ============================================================
# 传统编程：你写"规则" → 程序处理"数据" → 输出"答案"
# 机器学习：你给"数据 + 答案" → 算法自动学出"规则" → 用规则预测新数据
#
# 例子：识别猫
#   传统：你写"耳朵尖、有胡须、瞳孔..."等规则（写不完）
#   ML  ：给几万张图（标注"猫/非猫"）→ 算法自己学会判断
#
# 核心术语：
#   特征 Feature  ：输入（X），如 [身高, 体重, 年龄]
#   标签 Label    ：输出（y），如 [是否患病]
#   训练 Training ：用数据让模型学参数
#   预测 Predict  ：用学好的模型对新数据判断


# ============================================================
# 二、机器学习的三大类任务
# ============================================================
#
# (1) 监督学习 Supervised Learning（最常用，本模块重点）
#     数据"带标签"，目标是学输入→输出的映射
#     ├─ 分类 Classification：标签是"类别"（离散）
#     │   例：邮件是否垃圾邮件、图片是猫还是狗、肿瘤良恶性
#     └─ 回归 Regression：标签是"数值"（连续）
#         例：预测房价、温度、销售额
#
# (2) 无监督学习 Unsupervised Learning
#     数据"无标签"，目标是发现数据内在结构
#     ├─ 聚类 Clustering：把相似的样本分组
#     │   例：用户分群、异常检测
#     └─ 降维 Dimensionality Reduction：压缩特征
#         例：可视化高维数据、加速训练
#
# (3) 强化学习 Reinforcement Learning（本模块不涉及）
#     通过"试错 + 奖励"学习策略，如下棋、游戏 AI


# ============================================================
# 三、关键概念：训练集 vs 测试集
# ============================================================
# 为什么不能"用全部数据训练，再用同样的数据评估"？
# 因为模型可能"死记硬背"训练数据（过拟合），对新数据表现差。
# 标准做法：把数据切成两部分
#   - 训练集 train：用来训练（约占 70%~80%）
#   - 测试集 test ：用来评估（约占 20%~30%）
# 只有在测试集上的表现，才能反映模型的"真实能力"。

# 例子：学生平时刷的题(训练集) vs 期末考的题(测试集)
# 用平时刷过的题考自己 = 100分，但不代表真懂；要拿没见过的题考才行。


# ============================================================
# 四、关键概念：过拟合 vs 欠拟合
# ============================================================
# 欠拟合 Underfitting：模型太简单，连训练集都学不好
#   例：用一条直线拟合明显是曲线的数据
#   表现：训练集分数低、测试集分数也低
#
# 过拟合 Overfitting：模型太复杂，把训练数据的"噪声"也背下来了
#   例：决策树把每个样本都单独分到一个叶子
#   表现：训练集分数极高、测试集分数低（差距大）
#
# 好模型：训练集和测试集表现都好且接近（泛化能力强）


# ============================================================
# 五、Scikit-learn 标准 4 步工作流（必须背下来！）
# ============================================================
# 所有 sklearn 算法都遵循同一套接口，4 步即可完成建模：

# Step 1: 准备数据 X（特征）和 y（标签）
iris = load_iris()
X = iris.data            # shape (150, 4)：150 朵花 × 4 个特征
y = iris.target          # shape (150,)：每朵花的品种 0/1/2
print("特征形状:", X.shape, " 标签形状:", y.shape)
print("特征名:", iris.feature_names)
print("类别名:", iris.target_names)
print("前 5 行特征:\n", X[:5])

# Step 2: 划分训练集 / 测试集（必须做！）
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42, stratify=y
)
# test_size=0.3    测试集占 30%
# random_state=42  固定随机种子，保证每次运行结果一样（可复现）
# stratify=y       按 y 比例分层抽样，保证训练/测试集各类别比例一致

print(f"\n训练集: {X_train.shape[0]} 样本")
print(f"测试集: {X_test.shape[0]} 样本")

# Step 3: 创建模型并训练（fit）
model = KNeighborsClassifier(n_neighbors=3)   # KNN，k=3
model.fit(X_train, y_train)                   # 训练！就这一行

# Step 4: 预测并评估
y_pred = model.predict(X_test)                # 在测试集上预测
acc = accuracy_score(y_test, y_pred)          # 计算准确率
print(f"\n测试集准确率: {acc:.4f}")             # ~0.978

# 预测新样本
new_flower = [[5.1, 3.5, 1.4, 0.2]]           # 一朵新花的 4 个特征
pred = model.predict(new_flower)
print(f"新样本预测类别: {iris.target_names[pred[0]]}")


# ============================================================
# 六、Scikit-learn 的统一接口（核心记忆！）
# ============================================================
# 所有模型（不管多复杂）都用同样 4 个方法：
#   model = estimator(...)   # 创建
#   model.fit(X, y)          # 训练（监督）；无监督只有 fit(X)
#   model.predict(X)         # 预测
#   model.score(X, y)        # 评估（返回准确率或 R²）
#   model.transform(X)       # 转换（预处理/降维类用）
#
# 这意味着：换算法只需改一行（类名不同），其余代码完全一样！
# 这是 sklearn 设计的精妙之处：一致性。
#
# 例：把 KNN 换成逻辑回归，只改一行
