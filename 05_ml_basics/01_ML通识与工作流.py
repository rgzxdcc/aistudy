# 小结：本课建立的核心认知
# ============================================================
# 1. ML = 用数据自动学规则；监督学习带标签、无监督不带
# 2. 分类(离散标签) vs 回归(连续标签)是监督学习的两大任务
# 3. 必须划分训练/测试集，避免"自我感觉良好"
# 4. 警惕过拟合：训练好但测试差 = 没泛化能力
# 5. 标准 4 步：准备数据 → train_test_split → fit → predict/score
# 6. sklearn 统一接口：fit / predict / score / transform
