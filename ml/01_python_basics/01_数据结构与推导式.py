# ============================================================
# 一、列表 list —— 有序、可变，ML 中最常用的序列容器
# ============================================================
# 列表相当于其他语言里的"动态数组"，元素类型可混合，且可增删改。

fruits = ["apple", "banana", "cherry"]   # 方括号创建
print("列表:", fruits)

# 常用操作
fruits.append("date")        # 末尾追加
fruits.insert(0, "avocado")  # 指定位置插入
fruits.remove("banana")      # 按值删除
print("操作后:", fruits)

# 索引与切片（Python 特色：负索引、切片语法 seq[start:stop:step]）
print("第一个:", fruits[0])      # 正索引从 0 开始
print("最后一个:", fruits[-1])   # 负索引从末尾倒数
print("切片 [1:3]:", fruits[1:3])  # 取索引 1、2（不含 3）
print("反转:", fruits[::-1])      # step=-1 整体翻转

# 【ML 场景】列表常用于存放一行样本/一组标签
sample = [1.7, 65.0, 30]   # 例如 [身高, 体重, 年龄]
label = 1                  # 例如 1=患病, 0=健康


# ============================================================
# 二、元组 tuple —— 有序、不可变，常用于"固定结构的数据"
# ============================================================
# 元组创建后不能修改，速度比列表快，常作函数多返回值或字典的键。

point = (3, 4)            # 圆括号创建
x, y = point              # 解包（unpacking）：ML 中拆分特征/标签很常见
print("解包:", x, y)

# 【ML 场景】函数返回多个值
def min_max(data):
    return min(data), max(data)   # 实际返回的是元组

lo, hi = min_max([3, 1, 4, 1, 5])
print("最小/最大:", lo, hi)


# ============================================================
# 三、字典 dict —— 键值对，ML 中存放配置、样本、结果
# ============================================================
# 字典是 Python 里最高频的结构，键必须不可变（str/int/tuple）。

student = {"name": "小明", "age": 20, "score": 95.5}
print("字典:", student)
print("按键取值:", student["name"])

# 安全取值：键不存在时不会报错
print("安全取值:", student.get("gender", "未填写"))

# 遍历键 / 值 / 键值对
for k, v in student.items():       # .items() 同时拿到键和值
    print(f"  {k} = {v}")          # f-string 格式化字符串（Python 推荐）

# 【ML 场景】用字典描述一条样本：键=特征名，值=特征值
record = {"height": 1.7, "weight": 65.0, "label": "正常"}


# ============================================================
# 四、集合 set —— 无序、元素唯一，用于去重和成员判断
# ============================================================
nums = [1, 2, 2, 3, 3, 3, 4]
unique = set(nums)         # 一行去重
print("去重:", unique)      # {1, 2, 3, 4}

# 集合运算：交集 & 并集 | 差集 -
a = {1, 2, 3}
b = {3, 4, 5}
print("交集:", a & b, "并集:", a | b, "差集:", a - b)


# ============================================================
# 五、推导式 comprehension —— Python 的"特色表达力"，必学！
# ============================================================
# 推导式用一行完成"循环 + 过滤 + 构造"，ML 代码里随处可见。

# 5.1 列表推导式：[表达式 for 变量 in 可迭代对象 if 条件]
squares = [i ** 2 for i in range(1, 6)]           # 生成 1~5 的平方
print("平方:", squares)

evens = [i for i in range(10) if i % 2 == 0]      # 过滤偶数
print("偶数:", evens)

# 【ML 场景】对一组特征做归一化（缩放到 0~1）
heights = [160, 170, 180, 190]
h_min, h_max = min(heights), max(heights)
normalized = [(h - h_min) / (h_max - h_min) for h in heights]
print("归一化后:", normalized)   # [0.0, 0.33, 0.66, 1.0]

# 5.2 字典推导式：{键表达式: 值表达式 for ...}
word_len = {w: len(w) for w in ["cat", "bird", "fish"]}
print("词长字典:", word_len)     # {'cat': 3, 'bird': 4, 'fish': 4}


# ============================================================
# 六、可迭代与 enumerate / zip —— 遍历的常用利器
# ============================================================
# enumerate：同时拿到"索引"和"元素"（替代其他语言的 for i=0; i<n; i++）
names = ["Alice", "Bob", "Carol"]
for idx, name in enumerate(names):
    print(f"  第{idx}个: {name}")

# zip：把多个序列"并行"打包，ML 中常把特征与标签对齐
features = [[1.7, 65], [1.6, 55], [1.8, 80]]
labels = [0, 0, 1]
for feat, lab in zip(features, labels):
    print(f"  特征{feat} -> 标签{lab}")


