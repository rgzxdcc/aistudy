# -*- coding: utf-8 -*-
"""
模块3 · 第3课：选择、过滤、排序
================================
本课解决"如何精确取出我要的数据"——这是数据分析每天都要做的事。
核心是 loc / iloc 两个"取数神器"，以及条件过滤。
"""
import os
import numpy as np
import pandas as pd


# ============================================================
# 一、准备数据
# ============================================================
HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "..", "06_datasets", "students.csv")

df = pd.read_csv(CSV_PATH, encoding="utf-8-sig")
print("=== 原始数据 ===")
print(df)


# ============================================================
# 二、选列（回顾）
# ============================================================
# 单列 → Series
print("\n分数列:", df["分数"].tolist())

# 多列 → DataFrame（传入列名列表）
print("\n姓名+分数:\n", df[["姓名", "分数"]])


# ============================================================
# 三、loc vs iloc —— 最重要也最容易混的两个方法
# ============================================================
# 【核心区别】
# loc  : 用"标签"索引（行名/列名），切片"含尾"
# iloc : 用"位置"索引（整数0,1,2...），切片"不含尾"

# 3.1 选行
print("\n--- loc 用标签 ---")
print("第 0 行(loc[0]):\n", df.loc[0])              # 标签 0
print("第 0~1 行(loc[0:2]，含尾):\n", df.loc[0:2])  # 含标签 2！

print("\n--- iloc 用位置 ---")
print("第 0 行(iloc[0]):\n", df.iloc[0])
print("第 0~1 行(iloc[0:2]，不含尾):\n", df.iloc[0:2])   # 不含位置 2

# 3.2 同时选行列：loc[行, 列]
print("\nloc[0:2, ['姓名','分数']]:")
print(df.loc[0:2, ["姓名", "分数"]])        # 标签切片含尾

print("\niloc[0:2, 0:2]:")                  # 位置切片不含尾
print(df.iloc[0:2, 0:2])

# 口诀记忆：
#   看到 loc 就想"标签"，看到 iloc 就想"位置 0,1,2"
#   loc 切片像 Python 索引但"含尾"；iloc 切片"不含尾"（和 Python 一致）


# ============================================================
# 四、条件过滤（ML 选子集最常用！）
# ============================================================
# 类似 NumPy 的布尔索引，但写法更接近 SQL

# 4.1 单条件
female = df[df["性别"] == "女"]
print("\n女生:\n", female)

# 4.2 多条件：& (与) | (或)，每个条件必须加括号！
result = df[(df["分数"] >= 80) & (df["性别"] == "男")]
print("\n80分以上的男生:\n", result)

# 4.3 字符串条件：.str.contains 包含 / .str.startswith 开头
df["姓名"].astype(str)                       # 确保
beijing = df[df["城市"] == "北京"]
print("\n北京的:\n", beijing)

# 4.4 isin：在指定集合中（多值匹配）
target_cities = ["北京", "上海"]
big_city = df[df["城市"].isin(target_cities)]
print("\n北京或上海:\n", big_city)


# ============================================================
# 五、排序
# ============================================================
# sort_values(by=...) 按值排序；ascending=False 降序

# 单列排序
sorted_by_score = df.sort_values("分数", ascending=False)
print("\n按分数降序:\n", sorted_by_score[["姓名", "分数"]])

# 多列排序：先按性别，再按分数
multi_sorted = df.sort_values(["性别", "分数"], ascending=[True, False])
print("\n先性别后分数:\n", multi_sorted[["姓名", "性别", "分数"]])

# sort_index 按索引排序（较少用）
print("\n按索引降序:\n", df.sort_index(ascending=False).head(3))


# ============================================================
# 六、行列转置与 apply（数据变换）
# ============================================================
# 6.1 apply：对列/行应用函数（ML 特征工程核心）
# 把分数映射成等级
def to_grade(score):
    if pd.isna(score):
        return "未知"
    if score >= 90:
        return "优秀"
    if score >= 60:
        return "及格"
    return "不及格"

df["等级"] = df["分数"].apply(to_grade)        # 对"分数"列逐元素应用
print("\n新增等级列:\n", df[["姓名", "分数", "等级"]])

# 6.2 apply + lambda（更简洁）
df["年龄组"] = df["年龄"].apply(lambda a: "成年" if pd.notna(a) and a >= 20 else "未成年")
print("\n新增年龄组:\n", df[["姓名", "年龄", "年龄组"]])

# 6.3 map：Series 专用，常用于类别编码
# 【ML 场景】把"性别"文字编码成数字（机器学习模型只认数字）
df["性别编码"] = df["性别"].map({"男": 0, "女": 1})
print("\n性别编码:\n", df[["姓名", "性别", "性别编码"]])


# ============================================================
# 七、实战：ML 数据预处理"选取特征和标签"
# ============================================================
# 假设要预测"分数"，那么：
#   特征 X = 年龄、性别编码、城市等
#   标签 y = 分数

# 去掉缺失行（下一课详讲）
clean = df.dropna(subset=["分数"])

# 特征列
feature_cols = ["年龄", "性别编码"]
X = clean[feature_cols].copy()
y = clean["分数"].copy()
print("\n=== ML 切分 ===")
print("X 形状:", X.shape, " y 形状:", y.shape)
print("X 前几行:\n", X.head())


