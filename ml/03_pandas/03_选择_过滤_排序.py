# 小结：本课你应掌握的"ML 高频"操作
# ============================================================
# 1. loc（标签，切片含尾）vs iloc（位置，切片不含尾）—— 必须分清！
# 2. 条件过滤：df[df["列"] > x]；多条件 & |，注意加括号
# 3. isin 多值匹配；str 系列做字符串筛选
# 4. sort_values 多列排序，ascending 可分别指定
# 5. apply 应用函数（特征工程核心）；map 类别编码
# 6. 经典切分：X = df[特征列]; y = df[标签列]
